/**
 * 방 코드를 손질한다. 주소창의 `?room=`은 아무나 아무 글자나 넣을 수 있는 자리다.
 *
 * 실제로 겪었다. 친구가 주소창에 60자짜리 문자열을 넣고 들어왔더니, 그 코드가 방 이름
 * 옆에 그대로 찍혀 **상단 줄이 세 줄로 부풀고 화면이 무너졌다.** 화면만 고치면 이번
 * 자리는 막히지만, 코드는 링크·자리 지도·방 목록의 열쇠로도 쓰이므로 들어오는 문에서
 * 한 번 손질하는 편이 낫다.
 *
 * 문자 자체는 넓게 받는다. `?room=피자`처럼 원하는 말을 코드로 쓰는 것은 이 게임이
 * 권해온 사용법이라(README) 한글도 그대로 둔다. 다만 눈에 안 보이면서 자리만 차지하거나
 * 줄을 바꾸는 글자는 걷어낸다 — 통화로 불러줄 수 없는 코드는 코드가 아니다.
 */
export const ROOM_CODE_MAX = 12;

export function normalizeRoomCode(raw: string): string {
  return String(raw ?? '')
    // 제어문자와 공백류(줄바꿈·탭·전각공백 포함)를 걷어낸다
    .replace(/[\s\u0000-\u001f\u007f-\u009f\u200b-\u200f\u2028\u2029\ufeff]/g, '')
    .toUpperCase()
    // 자르는 것은 마지막이다. 먼저 자르면 걷어낼 글자가 자리를 차지한 채로 남는다.
    .slice(0, ROOM_CODE_MAX);
}
