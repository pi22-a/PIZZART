/**
 * 그리기 팔레트 18색.
 *
 * 색 개수를 정할 때 참고한 것: "한 번에 구분할 수 있는 색은 8~12개가 한계"라는 이야기가
 * 흔한데, 그건 **색이 뜻을 나르는 경우**(범례를 보고 어느 색이 무엇인지 외워야 하는 경우)의
 * 한계다. 그림 팔레트는 그 문제를 안 겪는다 — 사과를 그리니까 빨강을 고르는 것이라
 * 외울 것이 없다. 그래서 18색으로 잡았다.
 *
 * 다만 **낙서판의 색은 "누가 그렸나"를 나르므로** 그 한계가 그대로 적용된다. 그래서
 * 낙서판도 팔레트는 이걸 그대로 쓰되, 처음 배정되는 색은 앞에서부터 서로 다르게 준다
 * (Session.ensureDoodleColor).
 *
 * 배치는 3줄 × 6칸이다. 첫 줄은 무채색과 자연색, 둘째 줄은 따뜻한 쪽, 셋째 줄은 찬 쪽이라
 * 손이 기억하기 쉽다. 빨강부터 보라까지(빨주노초파남보)가 둘째·셋째 줄에 순서대로 들어간다.
 *
 * 흰색은 일부러 뺐다. 캔버스가 크림색(#f6efe2)이라 흰색으로 그으면 안 보이고,
 * 사람들은 그걸 "지우개"나 고장으로 읽는다. 지우개는 따로 있다.
 */
export const PALETTE = [
  // 무채색과 자연색
  '#1f1b17', '#4a4340', '#8d857e', '#8a5a2b', '#c98a4b', '#e8b48a',
  // 따뜻한 쪽 — 빨강 주황 노랑 연두 초록 청록
  '#e03131', '#f76707', '#eab308', '#94c748', '#2f9e44', '#0ca678',
  // 찬 쪽 — 하늘 파랑 남색 보라 자주 분홍
  '#4dabf7', '#1971c2', '#3b3f9e', '#7048e8', '#ae3ec9', '#e64980',
] as const;

/** 팔레트 이름. 화면에 툴팁으로 붙는다 — 색맹인 사람은 색만으로는 못 고른다. */
export const PALETTE_NAMES = [
  '검정', '진회색', '회색', '갈색', '황토', '살구',
  '빨강', '주황', '노랑', '연두', '초록', '청록',
  '하늘', '파랑', '남색', '보라', '자주', '분홍',
] as const;

/** 아무것도 안 고르면 검정이다. 지금까지의 그림과 같은 색이라 갑자기 달라 보이지 않는다. */
export const DEFAULT_COLOR: string = PALETTE[0];

/**
 * 서버가 색을 검사한다. 클라이언트가 보낸 값을 그대로 믿으면 배경과 같은 색으로 그어
 * "안 보이는 그림"을 만들 수 있고, 그러면 아무도 못 맞힌다.
 */
export function safeColor(c: unknown): string {
  return typeof c === 'string' && (PALETTE as readonly string[]).includes(c) ? c : DEFAULT_COLOR;
}
